// Direct same-origin worker files avoid bundler runtime bootstrap URL fragments.
import { build } from 'esbuild';
import { createHash } from 'node:crypto';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const entries = { schema: 'lib/developer-data/schema.worker.ts', sass: 'lib/utility-design/sass.worker.ts' };

export async function bundleWorkers(names = Object.keys(entries)) {
  return Promise.all(names.map(async name => {
    if (!Object.hasOwn(entries, name)) throw Error(`Unknown worker: ${name}`);
    const result = await build({ absWorkingDir: root, entryPoints: [entries[name]], bundle: true, write: false, platform: 'browser', format: 'iife', target: 'es2020', minify: true, metafile: true, legalComments: 'inline' });
    if (Object.values(result.metafile.outputs).some(output => output.imports.length)) throw Error(`Worker ${name} has external runtime dependencies`);
    if (result.outputFiles.length !== 1) throw Error(`Worker ${name} must be a self-contained file`);
    const contents = result.outputFiles[0].text;
    const hash = createHash('sha256').update(contents).digest('hex').slice(0, 16);
    return { name, filename: `${name}-${hash}.js`, contents, inputs: Object.keys(result.metafile.inputs) };
  }));
}
export async function generateWorkers() {
  const bundles = await bundleWorkers();
  const assets = path.join(root, 'public/generated-workers');
  const modules = path.join(root, 'lib/generated');
  await mkdir(assets, { recursive: true });
  await mkdir(modules, { recursive: true });
  for (const bundle of bundles) await writeFile(path.join(assets, bundle.filename), bundle.contents);
  const urls = Object.fromEntries(bundles.map(bundle => [bundle.name, `/generated-workers/${bundle.filename}`]));
  await writeFile(path.join(modules, 'browser-worker-urls.ts'), `// Generated by scripts/build-browser-workers.mjs. Do not edit.\nconst basePath = process.env.NEXT_PUBLIC_BASE_PATH || '';\nconst paths = ${JSON.stringify(urls, null, 2)} as const;\nexport const browserWorkerURLs = { schema: basePath + paths.schema, sass: basePath + paths.sass };\n`);
  return bundles;
}
if (process.argv[1] && pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url) {
  const bundles = await generateWorkers();
  console.log(`Generated browser workers: ${bundles.map(bundle => bundle.filename).join(', ')}`);
}
