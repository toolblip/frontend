#!/usr/bin/env node
/**
 * Pre-build script: scans blog markdown directories and generates
 * a static TypeScript manifest. Uses gray-matter for proper YAML parsing.
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import matter from 'gray-matter';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');

// content/blog is authoritative — scan it first so edits there win over any
// stale duplicate under src/content/blog (see docs/gsc-recovery-plan.md).
const BLOG_DIRS = [
  path.join(ROOT, 'content/blog'),
  path.join(ROOT, 'src/content/blog'),
];

const OUT_DIR = path.join(ROOT, 'content');
const OUT_FILE = path.join(OUT_DIR, 'blog-manifest.ts');

const DATE_PREFIX_RE = /^\d{4}-\d{2}-\d{2}-/;

function stripDatePrefix(slug) {
  return slug.replace(DATE_PREFIX_RE, '');
}

function canonicalSlug(filename, dataSlug) {
  return dataSlug && typeof dataSlug === 'string' && dataSlug.trim().length > 0
    ? dataSlug.trim()
    : filename.replace(/\.mdx?$/, '');
}

function normalizeDateValue(value) {
  if (typeof value === 'string') return value;
  if (value instanceof Date) return value.toISOString();
  return '';
}

// Collect all blog files, deduplicating
const seenPaths = new Set();
const postsBySlug = new Map();

for (const dir of BLOG_DIRS) {
  if (!fs.existsSync(dir)) continue;

  for (const filename of fs.readdirSync(dir)) {
    if (!filename.endsWith('.md') && !filename.endsWith('.mdx')) continue;
    const filePath = path.join(dir, filename);
    if (seenPaths.has(filePath)) continue;
    seenPaths.add(filePath);

    const raw = fs.readFileSync(filePath, 'utf-8');
    const { data, content } = matter(raw);
    const slug = canonicalSlug(filename, data.slug);

    if (!postsBySlug.has(slug)) {
      postsBySlug.set(slug, { slug, data, content });
    }
  }
}

const entries = [...postsBySlug.values()]
  .sort((a, b) => {
    const da = normalizeDateValue(a.data.date ?? a.data.publishDate ?? '');
    const db = normalizeDateValue(b.data.date ?? b.data.publishDate ?? '');
    return new Date(db).getTime() - new Date(da).getTime();
  })
  .map((f) => ({
    slug: f.slug,
    title: f.data.title ?? '',
    description: f.data.description ?? '',
    date: normalizeDateValue(f.data.date ?? f.data.publishDate ?? ''),
    category: f.data.category ?? '',
    tags: Array.isArray(f.data.tags) ? f.data.tags : [],
    author: f.data.author ?? 'Toolblip Team',
    readingTime: f.data.readingTime ?? '3 min',
    emoji: f.data.emoji ?? '📝',
    featuredImage: f.data.featuredImage ?? null,
    content: f.content ?? '',
  }));

const manifest = `// Auto-generated by scripts/generate-blog-manifest.mjs
// Run \`node scripts/generate-blog-manifest.mjs\` to regenerate (prebuild).

export interface BlogManifestEntry {
  slug: string;
  title: string;
  description: string;
  date: string;
  category: string;
  tags: string[];
  author: string;
  readingTime: string;
  emoji: string;
  featuredImage: string | null;
  content: string;
}

export const blogPosts: BlogManifestEntry[] = ${JSON.stringify(entries, null, 2)};
`;

fs.mkdirSync(OUT_DIR, { recursive: true });
fs.writeFileSync(OUT_FILE, manifest, 'utf-8');

console.log(`✓ Blog manifest: ${OUT_FILE} (${entries.length} posts)`);
