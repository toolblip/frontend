/** Browser-side scan of an image file for AI-provenance labels it declares about itself.
 * It reads C2PA (Content Credentials) manifests, IPTC DigitalSourceType values and
 * generator text in metadata. It cannot read pixel watermarks such as SynthID, and it
 * does not verify C2PA signatures.
 */

export type ProvenanceVerdict = 'ai-labeled' | 'credentials-no-ai-label' | 'no-signals';

export type ProvenanceReport = {
  verdict: ProvenanceVerdict;
  hasC2pa: boolean;
  digitalSourceTypes: string[];
  generators: string[];
  softwareAgents: string[];
  hasAiParameters: boolean;
};

// IPTC NewsCodes digital source types (https://cv.iptc.org/newscodes/digitalsourcetype/).
const SOURCE_TYPE_LABELS: Record<string, { label: string; ai: boolean }> = {
  trainedAlgorithmicMedia: { label: 'Generated by AI (trainedAlgorithmicMedia)', ai: true },
  compositeWithTrainedAlgorithmicMedia: { label: 'Edited or composited with AI (compositeWithTrainedAlgorithmicMedia)', ai: true },
  algorithmicallyEnhanced: { label: 'Algorithmically enhanced (algorithmicallyEnhanced)', ai: true },
  algorithmicMedia: { label: 'Algorithmic media, not AI-trained (algorithmicMedia)', ai: false },
  compositeSynthetic: { label: 'Composite including synthetic elements (compositeSynthetic)', ai: false },
  digitalCapture: { label: 'Captured by a camera (digitalCapture)', ai: false },
  digitalArt: { label: 'Digital art made by a person (digitalArt)', ai: false },
  composite: { label: 'Composite of captured elements (composite)', ai: false },
  minorHumanEdits: { label: 'Minor human edits (minorHumanEdits)', ai: false },
  screenCapture: { label: 'Screen capture (screenCapture)', ai: false },
  virtualRecording: { label: 'Virtual recording (virtualRecording)', ai: false },
  negativeFilm: { label: 'Scanned negative film (negativeFilm)', ai: false },
  positiveFilm: { label: 'Scanned positive film (positiveFilm)', ai: false },
  print: { label: 'Scanned print (print)', ai: false },
};

// Long, AI-specific strings only, so a random match in compressed pixel bytes is not realistic.
const GENERATORS: Array<[RegExp, string]> = [
  [/Adobe Firefly/, 'Adobe Firefly'],
  [/DALL[·\-· ]?E/, 'OpenAI DALL·E'],
  [/ChatGPT|OpenAI/, 'OpenAI'],
  [/Made with Google AI|Edited with Google AI|Imagen|Gemini/, 'Google AI'],
  [/Midjourney/i, 'Midjourney'],
  [/Stable Diffusion|stability\.ai/i, 'Stable Diffusion'],
  [/Microsoft Designer|Bing Image Creator|Microsoft Copilot/, 'Microsoft'],
  [/Meta AI|Imagined with AI/, 'Meta AI'],
  [/Ideogram/, 'Ideogram'],
  [/Leonardo\.Ai/i, 'Leonardo.Ai'],
  [/NovelAI/, 'NovelAI'],
  [/ComfyUI/, 'ComfyUI'],
  [/Flux\.1|black-forest-labs/i, 'FLUX'],
];

export function scanAiProvenance(bytes: Uint8Array): ProvenanceReport {
  // shortcut: scans the whole file as latin1 text instead of parsing JPEG/PNG/WebP segments and
  // CBOR; compressed PNG text (zTXt) is missed. Upgrade to a real C2PA parser if that matters.
  const text = latin1(bytes);

  const hasC2pa = /jumb/.test(text) && /c2pa/.test(text);

  const sourceTypeKeys = new Set<string>();
  for (const match of text.matchAll(/digitalsourcetype\/([A-Za-z]+)|DigitalSourceType[^A-Za-z]{1,8}([A-Za-z]+)/gi)) {
    const key = match[1] ?? match[2];
    if (key && SOURCE_TYPE_LABELS[key]) sourceTypeKeys.add(key);
  }
  for (const key of Object.keys(SOURCE_TYPE_LABELS)) {
    if (SOURCE_TYPE_LABELS[key].ai && text.includes(key)) sourceTypeKeys.add(key);
  }

  const generators = GENERATORS.filter(([pattern]) => pattern.test(text)).map(([, name]) => name);

  const softwareAgents = new Set<string>();
  // XMP history: softwareAgent="..." or <stEvt:softwareAgent>...</stEvt:softwareAgent>
  for (const match of text.matchAll(/softwareAgent(?:="([^"<]{1,80})"|>([^<]{1,80})<)/g)) {
    softwareAgents.add((match[1] ?? match[2]).trim());
  }
  // C2PA CBOR: claim_generator text, or claim_generator_info / softwareAgent maps with a "name".
  for (const match of text.matchAll(/claim_generator(?:_info)?|softwareAgent/g)) {
    const end = match.index + match[0].length;
    const nameAt = text.slice(end, end + 24).indexOf('dname');
    const value = readCborText(text, end) ?? (nameAt >= 0 ? readCborText(text, end + nameAt + 5) : null);
    if (value) softwareAgents.add(value);
  }

  // Stable Diffusion WebUI writes a "parameters" text chunk with Steps/Sampler/CFG values.
  const hasAiParameters = /Steps: \d+, Sampler: /.test(text);

  const digitalSourceTypes = [...sourceTypeKeys].map((key) => SOURCE_TYPE_LABELS[key].label);
  const aiSourceType = [...sourceTypeKeys].some((key) => SOURCE_TYPE_LABELS[key].ai);
  const verdict: ProvenanceVerdict = aiSourceType || generators.length > 0 || hasAiParameters
    ? 'ai-labeled'
    : hasC2pa || digitalSourceTypes.length > 0 ? 'credentials-no-ai-label' : 'no-signals';

  return { verdict, hasC2pa, digitalSourceTypes, generators, softwareAgents: [...softwareAgents].slice(0, 10), hasAiParameters };
}

function readCborText(text: string, pos: number): string | null {
  const head = text.charCodeAt(pos);
  let len = -1;
  let start = pos + 1;
  if (head >= 0x60 && head <= 0x77) len = head - 0x60;
  else if (head === 0x78) { len = text.charCodeAt(pos + 1); start = pos + 2; }
  if (len < 2) return null;
  const value = text.slice(start, start + len);
  return value.length === len && /^[\x20-\x7e]+$/.test(value) ? value.trim() : null;
}

function latin1(bytes: Uint8Array) {
  let out = '';
  const chunk = 0x8000;
  for (let i = 0; i < bytes.length; i += chunk) {
    out += String.fromCharCode(...bytes.subarray(i, i + chunk));
  }
  return out;
}
