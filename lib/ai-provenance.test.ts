import { describe, expect, it } from 'vitest';
import { scanAiProvenance } from './ai-provenance';

const enc = (...parts: Array<string | number[]>) => {
  const out: number[] = [];
  for (const part of parts) {
    if (typeof part === 'string') for (const ch of part) out.push(ch.charCodeAt(0));
    else out.push(...part);
  }
  return new Uint8Array(out);
};
const cborText = (s: string) => [...(s.length < 24 ? [0x60 + s.length] : [0x78, s.length]), ...Array.from(s, (c) => c.charCodeAt(0))];

describe('scanAiProvenance', () => {
  it('reports no signals for a plain image', () => {
    const report = scanAiProvenance(enc([0xff, 0xd8, 0xff, 0xe0], 'JFIF', [0, 1, 2, 0xff, 0xd9]));
    expect(report.verdict).toBe('no-signals');
    expect(report.hasC2pa).toBe(false);
  });

  it('reads an IPTC DigitalSourceType AI label from XMP', () => {
    const xmp = '<x:xmpmeta><rdf:Description Iptc4xmpExt:DigitalSourceType="http://cv.iptc.org/newscodes/digitalsourcetype/trainedAlgorithmicMedia" photoshop:Credit="Made with Google AI"/></x:xmpmeta>';
    const report = scanAiProvenance(enc([0xff, 0xd8], xmp));
    expect(report.verdict).toBe('ai-labeled');
    expect(report.digitalSourceTypes).toEqual(['Generated by AI (trainedAlgorithmicMedia)']);
    expect(report.generators).toEqual(['Google AI']);
  });

  it('detects a C2PA manifest and reads the CBOR claim generator and softwareAgent name', () => {
    const report = scanAiProvenance(enc(
      'jumb', [0, 0], 'jumdc2pa', [0, 1],
      [0x6f], 'claim_generator', cborText('Adobe_Photoshop/26.0'),
      [0x75], 'claim_generator_info', [0x81, 0xa1], [0x64], 'name', cborText('Camera App'),
      [0x6d], 'softwareAgent', [0xa1, 0x64], 'name', cborText('Adobe Firefly'),
    ));
    expect(report.hasC2pa).toBe(true);
    expect(report.softwareAgents).toEqual(['Adobe_Photoshop/26.0', 'Camera App', 'Adobe Firefly']);
    expect(report.generators).toEqual(['Adobe Firefly']);
    expect(report.verdict).toBe('ai-labeled');
  });

  it('marks Content Credentials without an AI label separately', () => {
    const report = scanAiProvenance(enc('jumb', 'c2pa', 'digitalsourcetype/digitalCapture'));
    expect(report.verdict).toBe('credentials-no-ai-label');
    expect(report.digitalSourceTypes).toEqual(['Captured by a camera (digitalCapture)']);
  });

  it('keeps composite AI labels distinct from fully generated ones', () => {
    const report = scanAiProvenance(enc('digitalsourcetype/compositeWithTrainedAlgorithmicMedia'));
    expect(report.digitalSourceTypes).toEqual(['Edited or composited with AI (compositeWithTrainedAlgorithmicMedia)']);
  });

  it('detects Stable Diffusion WebUI generation parameters', () => {
    const report = scanAiProvenance(enc([0x89], 'PNG', 'tEXtparameters', [0], 'a cat\nSteps: 20, Sampler: Euler a, CFG scale: 7'));
    expect(report.hasAiParameters).toBe(true);
    expect(report.verdict).toBe('ai-labeled');
  });

  it('reads XMP softwareAgent history entries', () => {
    const report = scanAiProvenance(enc('<stEvt:softwareAgent>Adobe Photoshop 25.0</stEvt:softwareAgent> stEvt:softwareAgent="GIMP 2.10"'));
    expect(report.softwareAgents).toEqual(['Adobe Photoshop 25.0', 'GIMP 2.10']);
  });
});
